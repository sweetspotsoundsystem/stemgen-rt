#!/usr/bin/env python3
"""Regenerate the experimental contract from the exported graph and EMA manifest."""
import argparse
import hashlib
import json
from pathlib import Path
import onnx

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('--model', type=Path, required=True)
p.add_argument('--checkpoints', type=Path, required=True)
a = p.parse_args()
graph = onnx.load(a.model)
metadata = {x.key: x.value for x in graph.metadata_props}
assert set(metadata) == {'stemgenrt.experimental'}
m = json.loads(metadata['stemgenrt.experimental'])
f = m['interface']
assert m['architecture']['source_order'] == ['drums', 'bass', 'vocals', 'other']
assert len(f['state_names']) == 13
assert f['input_shapes'][1:] == f['output_shapes'][1:]
settings = {
 'CONTRACT_ID': 'experimental-independent-dbv-40000-ema-fp32-v1',
 'MODEL_SHA256': hashlib.sha256(a.model.read_bytes()).hexdigest(),
 'MODEL_BYTE_SIZE': a.model.stat().st_size,
 # This is the identity of the three-checkpoint manifest, not a single checkpoint.
 'CHECKPOINT_SHA256': hashlib.sha256(a.checkpoints.read_bytes()).hexdigest(),
 'MODEL_STATE_SHA256': m['weight_sha256'],
 'SAMPLE_RATE': 44100, 'CHANNELS': 2, 'STEMS': 4, 'HOP_SAMPLES': 128,
 'ANALYSIS_WINDOW_SAMPLES': 1024, 'ANALYSIS_HISTORY_SAMPLES': 896,
 'SYNTHESIS_FRAME_SAMPLES': 256,
 'MODEL_OUTPUT_DELAY_CHUNKS': 1, 'ASYNC_QUEUE_DELAY_CHUNKS': 1,
 'PLUGIN_LATENCY_CHUNKS': 2, 'PLUGIN_LATENCY_SAMPLES': 256,
 'OUTPUT_ALIGNMENT': 'previous_input_chunk',
 'DRUMS_SOURCE_INDEX': 0, 'BASS_SOURCE_INDEX': 1, 'VOCALS_SOURCE_INDEX': 2,
 'OTHER_SOURCE_INDEX': 3, 'RESIDUAL_SOURCE_INDEX': 3,
 'INPUT_NAMES_CPP': ',\n    '.join(json.dumps(x) for x in f['input_names']),
 'OUTPUT_NAMES_CPP': ',\n    '.join(json.dumps(x) for x in f['output_names']),
 'STATE_SHAPES_CPP': ',\n    '.join('StateShape{{' + ', '.join(map(str, s + [0] * (4-len(s)))) + '}, ' + str(len(s)) + '}' for s in f['input_shapes'][1:]),
 'METADATA_JSON': metadata['stemgenrt.experimental'],
}
root = Path(__file__).resolve().parents[1]
text = 'include_guard(GLOBAL)\n\n# Generated by scripts/generate-independent-contract.py.\n# Experimental model identity lock; physical M4 performance is not qualified.\n# Analysis window/history constants describe the 1024-point carrier; bass\n# also carries a trailing 4096-point feature window in its own state.\n'
for key, value in settings.items():
    assert ']==]' not in str(value)
    text += f'set(STEMGENRT_QUALIFIED_{key} [==[{value}]==])\n'
(root / 'cmake/QualifiedModelContract.cmake').write_text(text)
